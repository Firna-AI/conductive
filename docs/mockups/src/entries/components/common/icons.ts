export type IconKey = keyof typeof icons

/** The keys of the icons, for the `enum` of a prop schema. */
export const iconKeys = Object.keys(icons).filter((key): key is IconKey =>
  Object.hasOwn(icons, key),
)

const keysByIcon = new Map<LucideIcon, IconKey>(
  iconKeys.map((key) => [icons[key], key]),
)

/**
 * The key of an icon that shared data holds, such as an icon of a menu that
 * the app reads too. An icon that the list leaves out fails the render.
 */
export function iconKeyOf(icon: LucideIcon): IconKey {
  const key = keysByIcon.get(icon)
  if (key === undefined) {
    throw new Error(`The icon ${icon.displayName ?? ''} has no key in icons.ts`)
  }
  return key
}
